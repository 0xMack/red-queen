"""The frontend data targets (publisher.frontend): each writes its file where it's told, from the stores."""

import json

import pytest
from trainer import train

from publisher import publish


def test_the_ballot_names_every_3_ply_opening_and_marks_the_level_ones(tmp_path):
    out = tmp_path / "ballot.ts"
    summary = publish({"target": "frontend.ballot", "params": {"out": str(out)}})
    assert summary["openings"] == 216 and summary["ballot"] == 174 and "garbage_collected" not in summary
    text = out.read_text(encoding="utf-8")
    assert text.startswith("// Generated by the publisher's frontend.ballot target")
    assert text.count('"ballot":true') == 174 and "export const BALLOT_PLIES = 3" in text


def test_a_pbt_run_is_written_as_its_population_history(tmp_path):
    spec = {"game": "checkers", "algorithm": "pbt", "budget": {"games": 40}, "seed": 3}
    spec["params"] = {"members": 4, "interval": 20, "depth": 1, "openings_per_pair": 1, "base": {"hidden": 4}}
    run_id = train({**spec, "tags": {"experiment": "e", "arm": "pbt"}})
    out = tmp_path / "pbt.ts"
    summary = publish(
        {"target": "frontend.pbt-history", "params": {"experiment": "e", "arm": "pbt", "seed": 3, "out": str(out)}}
    )
    assert summary["run_id"] == run_id and summary["generations"] == 2
    assert f'export const PBT_RUN = "{run_id[:8]}"' in out.read_text(encoding="utf-8")
    with pytest.raises(ValueError, match="not one"):
        publish({"target": "frontend.pbt-history", "params": {"experiment": "e", "arm": "nope", "out": str(out)}})


def test_a_tabular_run_is_written_with_its_curve_and_table(tmp_path):
    run_id = train(
        {
            "game": "snake",
            "algorithm": "rl.q_learning",
            "budget": {"iterations": 2},
            "held_out_every": 1,
            "params": {"steps_per_iteration": 2_000, "agent": {"epsilon_decay_steps": 2_000}},
        }
    )
    out = tmp_path / "rec.json"
    publish({"target": "frontend.rl-recording", "params": {"run": run_id[:8], "out": str(out)}})
    data = json.loads(out.read_text(encoding="utf-8"))
    assert data["run_id"] == run_id and data["algorithm"] == "q_learning" and len(data["values"]) == 2048 * 3
    assert [step for step, _ in data["curve"]] == [2_000, 4_000] and data["label"].startswith("q-learning on Snake")


def test_rl_curves_refuse_an_unknown_recording(tmp_path):
    with pytest.raises(ValueError, match="unknown recording"):
        publish({"target": "frontend.rl-curves", "params": {"names": ["nope"], "out": str(tmp_path)}})
