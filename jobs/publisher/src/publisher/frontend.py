"""Frontend data files (docs/design/0018 stage 7b): what the Learn chapters draw from real results, generated rather than
hand-written. Each is a publish target writing under `apps/frontend/app/data/` (or `params.out`), so it runs like any
job -- `redqueen export ballot` is `redqueen publish frontend.ballot --wait`. The files are checked in: regenerate one
when its source changes, then commit it.

- `frontend.ballot` -- every Checkers position three plies from the start, its board and material search's verdict;
  the level ones are the ballot (`checkersBallot.ts`, the "Measuring Strength" chapter).
- `frontend.pbt-history` -- one population-based training run's history: each member's round-robin score and settings
  per generation, and who copied whom (`pbtHistory.ts`, the "Who to Play" chapter).
- `frontend.rl-curves` -- chosen runs of a tracked RL experiment as recorded curves: held-out score, and mean Q or
  policy entropy, against env steps (`recordings/<name>.json`, the DQN and policy-gradient chapters).
- `frontend.rl-recording` -- a tabular run's curve and final Q-table, the Q-learning chapter's no-WebAssembly fallback
  (`recordings/q-learning-snake.json`).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from jobcore import Sink
from jobcore.specs import PublishSpec
from modelpack import LocalModelStore, QTable, load_champion
from telemetry import RunInfo, workspace_root

from publisher.registry import target


def _out(params: Any, default: str) -> Path:
    path = Path(params.out) if params.out else workspace_root() / "apps" / "frontend" / "app" / "data" / default
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def _wrote(path: Path, **summary: Any) -> dict[str, Any]:
    print(f"wrote {path} ({path.stat().st_size:,} bytes)", flush=True)
    return {"path": str(path), "bytes": path.stat().st_size, **summary}


# --- the ballot -----------------------------------------------------------------------------------------------------

CODES = {"red_man": "r", "red_king": "R", "black_man": "b", "black_king": "B"}


def _square(square: tuple[int, int]) -> str:
    x, y = square
    return f"{'abcdefgh'[x]}{y + 1}"


def describe_opening(opening: tuple[int, ...]) -> dict[str, Any]:
    from games.checkers import Checkers
    from games.checkers_openings import BALLOT_DEPTH, level_value

    env = Checkers()
    moves = []
    for index in opening:
        move = env.legal_moves()[index]
        moves.append(("x" if abs(move[1][0] - move[0][0]) == 2 else "-").join(_square(s) for s in move))
        env.step(move)
    labels = env.render_state()["cells"]
    # the 32 playable squares, row by row from Red's side: r/R a red man/king, b/B black, . empty
    board = "".join(CODES.get(labels.get((x, y)), ".") for y in range(8) for x in range(8) if (x + y) % 2 == 1)
    return {"moves": moves, "board": board, "value": level_value(opening, BALLOT_DEPTH)}


@target("frontend.ballot")
def ballot(spec: PublishSpec, params: Any, sink: Sink, store: LocalModelStore) -> dict[str, Any]:
    from games.checkers_openings import BALLOT_DEPTH, BALLOT_PLIES, all_openings
    from games.checkers_openings import ballot as chosen_openings

    chosen = set(chosen_openings())
    rows = [{**describe_opening(o), "ballot": o in chosen} for o in all_openings(BALLOT_PLIES)]
    body = ",\n".join("  " + json.dumps(r, separators=(",", ":")) for r in rows)
    path = _out(params, "checkersBallot.ts")
    path.write_bytes(
        (
            "// Generated by the publisher's frontend.ballot target (`redqueen export ballot`) -- do not edit. Every\n"
            f"// Checkers position three plies from the start ({len(rows)}), its moves, its board, and {BALLOT_DEPTH}-ply"
            " material search's\n"
            f"// value for the side to move (men 1, kings 2): the {len(chosen)} it scores level are the ballot every"
            " strength\n// measurement plays (docs/design/0013).\n"
            "// `board`: the 32 playable squares, row by row from Red's side (r/R a red man/king, b/B black, . empty).\n\n"
            "export interface BallotOpening {\n  moves: string[]\n  board: string\n  value: number\n  ballot: boolean\n}\n\n"
            f"export const BALLOT_PLIES = {BALLOT_PLIES}\nexport const BALLOT_DEPTH = {BALLOT_DEPTH}\n\n"
            f"export const openings: BallotOpening[] = [\n{body},\n]\n"
        ).encode()
    )
    return _wrote(path, openings=len(rows), ballot=len(chosen))


# --- a PBT run's history --------------------------------------------------------------------------------------------


def _tagged_run(sink: Sink, experiment: str, arm: str, seed: int) -> RunInfo:
    found = [
        r
        for r in sink.registry.list_runs()
        if r.config.get("experiment") == experiment
        and r.config.get("arm") == arm
        and r.config.get("rng_seed") == seed
        and r.status == "completed"
    ]
    if len(found) != 1:
        raise ValueError(f"{len(found)} completed runs of {experiment}/{arm} seed {seed}, not one")
    return found[0]


@target("frontend.pbt-history")
def pbt_history(spec: PublishSpec, params: Any, sink: Sink, store: LocalModelStore) -> dict[str, Any]:
    run = _tagged_run(sink, params.experiment, params.arm, params.seed)
    log = json.loads(sink.artifacts.get_program(f"{run.run_id}-population").decode("utf-8"))
    generations = [
        {
            "scores": [round(s, 3) for s in g["scores"]],
            # rounded for the page: the figure draws them, nothing recomputes from them
            "settings": [{k: round(v, 5) for k, v in s.items()} for s in g["settings"]],
            "copied": [list(pair) for pair in g["copied"]],
        }
        for g in log
    ]
    initial = [{k: round(v, 5) for k, v in s.items()} for s in run.config["initial_settings"]]
    path = _out(params, "pbtHistory.ts")
    path.write_bytes(
        (
            "// Generated by the publisher's frontend.pbt-history target (`redqueen export pbt-history`) -- do not edit.\n"
            f"// One population-based training run (docs/design/0014): {params.experiment} / {params.arm} / seed"
            f" {params.seed}, run {run.run_id[:8]}.\n"
            "// `generations[g].scores` are each member's points per game in that round robin; `settings` are what each\n"
            "// member trains with *after* the round (exploit/explore applied); `copied` lists [loser, winner] pairs;\n"
            "// `initial` is every member's sampled starting settings.\n\n"
            "export interface PbtSettings {\n  learning_rate: number\n  lambda: number\n  pool_fraction: number\n"
            "  pfsp: number\n}\n\n"
            "export interface PbtGeneration {\n  scores: number[]\n  settings: PbtSettings[]\n  copied: [number, number][]\n}\n\n"
            f"export const PBT_RUN = {json.dumps(run.run_id[:8])}\n"
            f"export const PBT_INTERVAL = {int(run.config['interval'])}\n"
            f"export const initial: PbtSettings[] = {json.dumps(initial)}\n"
            f"export const generations: PbtGeneration[] = {json.dumps(generations)}\n"
        ).encode()
    )
    return _wrote(path, run_id=run.run_id, generations=len(generations))


# --- recorded RL curves ---------------------------------------------------------------------------------------------

# recording -> (experiment, extra curves to keep, [(key, arm, rng seed, label)])
RECORDINGS: dict[str, tuple[str, list[str], list[tuple[str, str, int, str]]]] = {
    # the two DQN runs that diverged, a healthy one, and one run per observer (the DQN chapter)
    "dqn-snake": (
        "rl-dqn-v1",
        ["q_mean"],
        [
            ("naive-diverged", "dqn-naive", 0, "no replay, no target network (seed 0)"),
            ("replay-diverged", "dqn-replay", 3, "replay, no target network (seed 3)"),
            ("healthy", "dqn", 3, "replay + target network (seed 3)"),
            ("egocentric", "dqn", 0, "egocentric.v1 (27 inputs)"),
            ("features", "dqn-features", 0, "features.v1 (11 inputs)"),
            ("grid", "dqn-grid", 0, "grid-flat.v1 (100 inputs)"),
        ],
    ),
    # one run per rung of the policy-gradient ladder, same seed (the policy-gradients chapter)
    "pg-snake": (
        "rl-pg-v1",
        ["entropy"],
        [
            ("reinforce", "pg-reinforce", 0, "REINFORCE"),
            ("baseline", "pg-reinforce-baseline", 0, "REINFORCE + baseline"),
            ("a2c", "pg-a2c", 0, "A2C"),
            ("ppo", "pg-ppo", 0, "PPO"),
            ("ppo-ego2", "pg-ppo-ego2", 0, "PPO, egocentric.v2"),
        ],
    ),
}


def rl_curves_recording(sink: Sink, name: str) -> dict[str, Any]:
    experiment, extras, picks = RECORDINGS[name]
    out = {}
    for key, arm, seed, label in picks:
        run = _tagged_run(sink, experiment, arm, seed)
        history = sink.metrics.history(run.run_id)
        steps = [int((h.extras or {})["env_steps"]) for h in history]
        entry: dict[str, Any] = {
            "run_id": run.run_id,
            "label": label,
            "score": [
                [s, round(h.held_out_score, 2)]
                for s, h in zip(steps, history, strict=True)
                if h.held_out_score is not None
            ],
        }
        # %.4g keeps a diverged 1.3e10 and a healthy 2.63 alike readable
        if "q_mean" in extras:
            entry["q_mean"] = [
                [s, float(f"{(h.extras or {})['q_mean']:.4g}")] for s, h in zip(steps, history, strict=True)
            ]
        if "entropy" in extras:  # a policy's entropy is the run's `diversity` (docs/design/0010 Decision 3)
            entry["entropy"] = [[s, round(h.diversity, 4)] for s, h in zip(steps, history, strict=True)]
        out[key] = entry
    return {"experiment": experiment, "runs": out}


@target("frontend.rl-curves")
def rl_curves(spec: PublishSpec, params: Any, sink: Sink, store: LocalModelStore) -> dict[str, Any]:
    written = {}
    for name in params.names or list(RECORDINGS):
        if name not in RECORDINGS:
            raise ValueError(f"unknown recording {name!r} (known: {', '.join(RECORDINGS)})")
        path = Path(params.out) / f"{name}.json" if params.out else _out(params, f"recordings/{name}.json")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes((json.dumps(rl_curves_recording(sink, name), separators=(",", ":")) + "\n").encode())
        written[name] = _wrote(path)["path"]
    return {"written": written}


# --- a tabular run, recorded ----------------------------------------------------------------------------------------


@target("frontend.rl-recording")
def rl_recording(spec: PublishSpec, params: Any, sink: Sink, store: LocalModelStore) -> dict[str, Any]:
    matches = [r for r in sink.registry.list_runs() if r.run_id.startswith(params.run)]
    if len(matches) != 1:
        raise ValueError(f"{params.run!r} matches {len(matches)} runs")
    run = matches[0]
    history = sink.metrics.history(run.run_id)
    table = load_champion(sink.artifacts.get_program(history[-1].champion_ref).decode("utf-8"))
    if not isinstance(table, QTable):
        raise TypeError(f"run {run.run_id}'s champion isn't a Q-table")
    agent = run.config.get("params") or {}
    described = ", ".join(f"{k} {v:g}" for k, v in sorted(agent.items())) or "default parameters"
    data = {
        "run_id": run.run_id,
        "label": params.label
        or f"{run.config['representation'].replace('_', '-')} on Snake ({described}), rng seed {run.config['rng_seed']}",
        "algorithm": run.config["representation"],
        "params": agent,
        # a table carries no visit counts: a row still at its starting values was never updated
        "initial_q": agent.get("initial_q", 0.0),
        "curve": [
            [int((h.extras or {}).get("env_steps", 0)), round(h.held_out_score, 3)]
            for h in history
            if h.held_out_score is not None
        ],
        "values": [round(v, 4) for v in table.values],  # 4 decimals: the same moves, the same colours, a small file
    }
    path = _out(params, "recordings/q-learning-snake.json")
    path.write_bytes((json.dumps(data, separators=(",", ":")) + "\n").encode())
    return _wrote(path, run_id=run.run_id)
